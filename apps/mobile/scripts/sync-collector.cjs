// Copies the browser extension's page collector into the app as a string, for the in-app Coupang browser to inject.
// The phone app cannot import ../extension (outside the bundle) and Hermes keeps no function source, so the text is
// generated here. Run `npm run sync-collector` after changing apps/extension/collector.js; `--check` fails when stale.
const fs = require('node:fs');
const path = require('node:path');

const source = fs.readFileSync(path.resolve(__dirname, '../../extension/collector.js'), 'utf8');
const target = path.resolve(__dirname, '../lib/collectorSource.ts');
const generated = `// Generated by scripts/sync-collector.cjs from apps/extension/collector.js. Do not edit by hand.\n`
  + `export const collectorSource = ${JSON.stringify(source)};\n`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== generated) {
    console.error('lib/collectorSource.ts is out of date. Run: npm run sync-collector');
    process.exit(1);
  }
  console.log('collector source up to date');
} else {
  fs.writeFileSync(target, generated);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${source.length} chars)`);
}
